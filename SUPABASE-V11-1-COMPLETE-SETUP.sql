create policy "Applicants upload player documents"
on storage.objects
for insert
to anon, authenticated
with check (
  bucket_id='player-documents'
  and (storage.foldername(name))[1] in ('age-proofs','payment-receipts')
);

-- Only authenticated admins can view or remove private documents.
drop policy if exists "Admins read player documents" on storage.objects;
create policy "Admins read player documents"
on storage.objects
for select
to authenticated
using (
  bucket_id='player-documents'
  and (auth.jwt() -> 'app_metadata' ->> 'role')='admin'
);

drop policy if exists "Admins delete player documents" on storage.objects;
