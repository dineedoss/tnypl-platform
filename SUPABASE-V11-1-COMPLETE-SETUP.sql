-- ------------------------------------------------------------
-- 1. Ensure the player table has the operational status fields.
-- ------------------------------------------------------------
alter table if exists public.players
  add column if not exists payment_status text not null default 'pending',
  add column if not exists age_verification_status text not null default 'pending',
  add column if not exists draft_status text not null default 'not_eligible_yet',
  add column if not exists refund_status text not null default 'not_applicable',
  add column if not exists privacy_consent_at timestamptz,
  add column if not exists guardian_consent_at timestamptz,
  add column if not exists verified_at timestamptz,
  add column if not exists verified_by uuid,
  add column if not exists rejection_reason text,
  add column if not exists registration_reference text;

-- Fill a reference for existing rows when an id column is available.
do $block$
begin
  if to_regclass('public.players') is not null
     and exists (
       select 1 from information_schema.columns
       where table_schema='public' and table_name='players' and column_name='id'
     ) then
    execute $sql$
      update public.players
      set registration_reference =
        'TNYPL-' || to_char(coalesce(created_at, now()), 'YYYYMMDD') || '-' ||
        upper(substr(md5(id::text || coalesce(email,'')),1,6))
      where registration_reference is null
    $sql$;
  end if;
end
$block$;

-- ------------------------------------------------------------
-- 2. Audit history for verification, draft and refund actions.
-- ------------------------------------------------------------
create table if not exists public.player_audit_logs (
  id bigint generated by default as identity primary key,
  player_id text not null,
  action text not null,
  previous_value jsonb,
  new_value jsonb,
  notes text,
  acted_by uuid,
  created_at timestamptz not null default now()
);

create index if not exists player_audit_logs_player_idx
  on public.player_audit_logs(player_id);

create index if not exists player_audit_logs_created_idx
  on public.player_audit_logs(created_at desc);

alter table public.player_audit_logs enable row level security;
revoke all on public.player_audit_logs from anon;

drop policy if exists "Admins read audit logs" on public.player_audit_logs;
create policy "Admins read audit logs"
on public.player_audit_logs
for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Admins create audit logs" on public.player_audit_logs;
create policy "Admins create audit logs"
on public.player_audit_logs
for insert
to authenticated
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

