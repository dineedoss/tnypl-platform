  (6,'Day 3',p_start_date+2,p_second_time,'T30',p_venue,p_ground,b1,b3,'scheduled',true,'Generated by TNYPL V25 official draw',auth.uid()),
  (7,'Day 4',p_start_date+3,p_first_time,'T30',p_venue,p_ground,a2,a4,'scheduled',true,'Generated by TNYPL V25 official draw',auth.uid()),
  (8,'Day 4',p_start_date+3,p_second_time,'T30',p_venue,p_ground,b2,b4,'scheduled',true,'Generated by TNYPL V25 official draw',auth.uid()),
  (9,'Day 5',p_start_date+4,p_first_time,'T30',p_venue,p_ground,a1,a4,'scheduled',true,'Generated by TNYPL V25 official draw',auth.uid()),
