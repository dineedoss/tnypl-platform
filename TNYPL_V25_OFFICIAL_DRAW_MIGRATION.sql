     or b1 is null or b2 is null or b3 is null or b4 is null then
    raise exception 'All A1-A4 and B1-B4 positions must be assigned';
  end if;

  delete from public.matches
  where notes = 'Generated by TNYPL V25 official draw';

  insert into public.matches(
    match_number,match_day,match_date,start_time,format,venue,ground,
    home_franchise_id,away_franchise_id,status,is_published,notes,created_by
  )
